@lru_cache(maxsize=1)
def _full_course_placements() -> dict:
    # Source: the supplied advanced handout. Text and emphasis come from its tagged PDF.
    path = Path(__file__).resolve().parent.parent / 'data' / 'advanced_course_placements.json'
    return json.loads(path.read_text(encoding='utf-8'))


def get_full_course_placement(planet_key: str, house: int) -> dict | None:
    return _full_course_placements().get(f'{planet_key.lower()}-{house}')
